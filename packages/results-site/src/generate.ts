import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { deriveDecision, renderDecisionMemo } from "./decision.ts";
import { NON_EVIDENCE_LABEL, normalizeRow, PRODUCT_TRACE_THRESHOLD, SYNTHETIC_PIPELINE_LABEL } from "./examples.ts";
import type { LedgerRow, NormalizedRow } from "./examples.ts";
import { buildStats, renderAllTables, renderRateWithInterval } from "./tables.ts";

const GENERATED_NOTICE = "<!-- GENERATED by packages/results-site/src/generate.ts; do not hand-edit. -->";

type CliOptions = {
  ledgerPaths: string[];
  outDir: string;
  decisionOnly: boolean;
};

type LoadResult = {
  rows: NormalizedRow[];
  sourceDescription: string;
  warnings: string[];
  engineeringE2EComplete: boolean;
};

async function main(): Promise<void> {
  const options = parseArgs(process.argv.slice(2));
  const loaded = await loadRows(options.ledgerPaths);
  const decision = deriveDecision(loaded.rows, loaded.engineeringE2EComplete);
  const summary = buildSummary(loaded, decision);

  await mkdir(options.outDir, { recursive: true });

  if (!options.decisionOnly) {
    await writeFile(path.join(options.outDir, "index.md"), renderIndex(loaded, decision), "utf8");
    await writeFile(path.join(options.outDir, "summary.json"), `${JSON.stringify(summary, null, 2)}\n`, "utf8");
  }

  const decisionFile = decision.evidence_e2e_complete ? "30_DAY_DECISION.md" : "30_DAY_DECISION.blocked.md";
  await writeFile(path.join(options.outDir, decisionFile), renderDecisionMemo(decision, loaded.sourceDescription), "utf8");
  console.log(`generated ${options.outDir}${options.decisionOnly ? `/${decisionFile}` : "/index.md and /summary.json"}`);
}

function parseArgs(args: string[]): CliOptions {
  const ledgerPaths: string[] = [];
  let outDir = "docs/results";
  let decisionOnly = false;
  const normalizedArgs = args.filter((arg) => arg !== "--");

  for (let index = 0; index < normalizedArgs.length; index += 1) {
    const arg = normalizedArgs[index];
    if (arg === "--ledger") {
      const value = normalizedArgs[index + 1];
      if (!value) throw new Error("--ledger requires a path");
      ledgerPaths.push(value);
      index += 1;
    } else if (arg === "--out") {
      const value = normalizedArgs[index + 1];
      if (!value) throw new Error("--out requires a directory");
      outDir = value;
      index += 1;
    } else if (arg === "--decision-only") {
      decisionOnly = true;
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }

  return { ledgerPaths, outDir, decisionOnly };
}

async function loadRows(explicitLedgerPaths: string[]): Promise<LoadResult> {
  const warnings: string[] = [];
  const ledgerPaths = explicitLedgerPaths.length > 0 ? explicitLedgerPaths : await discoverLedgerPaths();

  if (ledgerPaths.length === 0) {
    warnings.push("No judged ledger found. Results are generated from an empty dataset and are blockers, not evidence.");
    return { rows: [], sourceDescription: "empty dataset (no eval/results/*/ledger-judged*.jsonl found)", warnings, engineeringE2EComplete: false };
  }

  const rows: NormalizedRow[] = [];
  for (const ledgerPath of ledgerPaths) {
    const content = await readFile(ledgerPath, "utf8");
    const lines = content.split(/\r?\n/);
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index].trim();
      if (!line) continue;
      try {
        rows.push(normalizeRow(JSON.parse(line) as LedgerRow, ledgerPath, index + 1));
      } catch (error) {
        throw new Error(`Failed to parse ${ledgerPath}:${index + 1}: ${(error as Error).message}`);
      }
    }
  }

  return { rows, sourceDescription: ledgerPaths.join(", "), warnings, engineeringE2EComplete: await readEngineeringGate(ledgerPaths) };
}

async function discoverLedgerPaths(): Promise<string[]> {
  const root = "eval/results";
  if (!(await exists(root))) return [];
  const runIds = (await readdir(root)).sort().reverse();
  for (const runId of runIds) {
    const runDir = path.join(root, runId);
    if (!(await isDirectory(runDir))) continue;
    const files = await readdir(runDir);
    const judged = files
      .filter((file) => /^ledger-judged.*\.jsonl$/.test(file))
      .map((file) => path.join(runDir, file))
      .sort();
    if (judged.length > 0) return judged;
  }
  return [];
}

function buildSummary(loaded: LoadResult, decision: ReturnType<typeof deriveDecision>): Record<string, unknown> {
  const stats = buildStats(loaded.rows);
  const syntheticSmoke = loaded.rows.filter((row) => row.provenanceType === "synthetic" || row.mode === "smoke" || !row.countsAsProductEvidence).length;
  const negativeRows = loaded.rows.filter((row) => row.negativeResult || row.harmFlags.length > 0).length;

  return {
    generated_by: "packages/results-site/src/generate.ts",
    generated_at: deterministicGeneratedAt(),
    source: loaded.sourceDescription,
    warnings: loaded.warnings,
    labels: syntheticSmoke > 0 || loaded.rows.length === 0 ? [NON_EVIDENCE_LABEL, SYNTHETIC_PIPELINE_LABEL] : [],
    engineering_e2e_complete: decision.engineering_e2e_complete,
    evidence_e2e_complete: decision.evidence_e2e_complete,
    product_decision: decision.decision,
    product_decision_kind: decision.decisionKind,
    thresholds: decision.thresholds,
    threshold_basis: decision.thresholdBasis,
    blockers: decision.blockers,
    stats,
    denominators: {
      ledger_rows: loaded.rows.length,
      distinct_traces: new Set(loaded.rows.map((row) => row.traceId)).size,
      required_product_traces: PRODUCT_TRACE_THRESHOLD,
      negative_rows: `${negativeRows}/${loaded.rows.length}`,
      synthetic_or_smoke_rows: `${syntheticSmoke}/${loaded.rows.length}`,
    },
  };
}

function renderIndex(loaded: LoadResult, decision: ReturnType<typeof deriveDecision>): string {
  const stats = buildStats(loaded.rows);
  const tables = renderAllTables(loaded.rows);
  const hasSyntheticOrEmpty = stats.syntheticOrSmokeRows > 0 || loaded.rows.length === 0;
  const warnings = loaded.warnings.length > 0 ? loaded.warnings.map((warning) => `- ${warning}`).join("\n") : "- none";
  const thresholdRows = Object.entries(decision.thresholds)
    .map(([name, passed]) => `| ${name} | ${passed ? "pass" : "fail"} | ${decision.thresholdBasis[name] ?? "n/a"} |`)
    .join("\n");
  const blockers = decision.blockers.length > 0 ? decision.blockers.map((blocker) => `- ${blocker}`).join("\n") : "- none";
  const negativeRows = loaded.rows.filter((row) => row.negativeResult || row.harmFlags.length > 0).length;

  return `${GENERATED_NOTICE}
# OpenClawBrain V5 Results

${hasSyntheticOrEmpty ? `> **${NON_EVIDENCE_LABEL}**  \n> **${SYNTHETIC_PIPELINE_LABEL}**\n\n` : ""}Source ledger: ${loaded.sourceDescription}

Decision: **${decision.decision}**

## Gate State

| Gate | Value | Basis / Denominator |
|---|---:|---|
| engineering_e2e_complete | ${decision.engineering_e2e_complete} | ${decision.engineering_e2e_complete ? "1/1" : "0/1"} RUN_STATE engineering gate |
| evidence_e2e_complete | ${decision.evidence_e2e_complete} | ${decision.blockers.length === 0 ? "all" : Object.keys(decision.thresholds).length - decision.blockers.length}/${Object.keys(decision.thresholds).length} thresholds |
| admitted real product traces | ${decision.traceCounts.admittedRealProductTraces}/${PRODUCT_TRACE_THRESHOLD} | required traces |
| total ledger rows | ${stats.totalRows}/${stats.totalRows} | rows / rows |
| distinct traces | ${stats.totalTraces}/${stats.totalTraces} | traces / traces |
| negative rows | ${negativeRows}/${stats.totalRows} | negative rows / all rows |

## Thresholds

| Threshold | Status | Basis / Denominator |
|---|---|---|
${thresholdRows}

## Blockers

${blockers}

## Warnings

${warnings}

## Uncertainty Snapshot

- Win rows: ${renderRateWithInterval(loaded.rows.filter((row) => row.outcome === "win").length, loaded.rows.length)}
- Harm rows: ${renderRateWithInterval(loaded.rows.filter((row) => row.outcome === "harm" || row.harmFlags.length > 0).length, loaded.rows.length)}
- Negative rows: ${renderRateWithInterval(negativeRows, loaded.rows.length)}

${tables.map((table) => `## ${table.title}\n\n${table.markdown}`).join("\n\n")}
`;
}

function deterministicGeneratedAt(): string | null {
  if (process.env.OCB_RESULTS_GENERATED_AT) return process.env.OCB_RESULTS_GENERATED_AT;
  if (process.env.SOURCE_DATE_EPOCH) {
    const epochSeconds = Number(process.env.SOURCE_DATE_EPOCH);
    if (Number.isFinite(epochSeconds)) return new Date(epochSeconds * 1000).toISOString();
  }
  return null;
}

async function exists(filePath: string): Promise<boolean> {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

async function isDirectory(filePath: string): Promise<boolean> {
  try {
    return (await stat(filePath)).isDirectory();
  } catch {
    return false;
  }
}

async function readEngineeringGate(ledgerPaths: string[]): Promise<boolean> {
  for (const ledgerPath of ledgerPaths) {
    const runStatePath = path.join(path.dirname(ledgerPath), "RUN_STATE.json");
    if (!(await exists(runStatePath))) continue;
    const raw = JSON.parse(await readFile(runStatePath, "utf8")) as { engineering_e2e_complete?: unknown };
    if (raw.engineering_e2e_complete === true) return true;
  }
  return false;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
